export const EMOJI_ENTRIES = new Map(
  EMOJI_CATEGORIES.flatMap((group) =>
    group.emojis.map((entry) => [entry.emoji, entry] as const),
  ),
);

const compact = (text: string) => text.toLowerCase().replace(/\s+/g, "");
const index = [...EMOJI_ENTRIES.values()].map((entry) => ({
  entry,
  name: compact(entry.name),
  keywords: entry.keywords.toLowerCase().split(/\s+/),
  words: compact(`${entry.keywords} ${entry.emoji}`),
}));

// The whole name or a search word comes first, then names that start with the
// query, other name matches and partial search words, each in catalog order.
// Spaces are ignored, so "웃는얼굴" finds "웃는 얼굴".
export function searchEmojis(query: string): EmojiEntry[] {
  const text = compact(query);
  if (!text) return [];
  const rank = (item: (typeof index)[number]) =>
    item.name === text || item.keywords.includes(text)
      ? 0
      : item.name.startsWith(text)
        ? 1
        : item.name.includes(text)
          ? 2
          : item.words.includes(text)
            ? 3
            : 4;
  return index
    .map((item) => ({ item, rank: rank(item) }))
    .filter(({ rank }) => rank < 4)
    .sort((a, b) => a.rank - b.rank)
    .map(({ item }) => item.entry);
}

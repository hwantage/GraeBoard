import { readFile, writeFile, mkdir } from "node:fs/promises";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
// Reuse the existing pure workbook parser/exporter verbatim. Their server module
// also imports SQLite and sharp, so generate only this dependency-free section.
export async function generateTransferCore() {
  const source = await readFile(resolve(root, "server/transfer.mjs"), "utf8"),
    start = source.indexOf("const aliases ="),
    end = source.indexOf("export function installTransferRoutes(");
  if (start < 0 || end < start)
    throw new Error(
      "Workbook source boundary changed; update Worker extraction",
    );
  const imports = `// Generated by scripts/build-worker.mjs from server/transfer.mjs; edit the original.\nimport ExcelJS from 'exceljs/dist/exceljs.min.js';\nimport { createHash } from 'node:crypto';\nimport { z } from 'zod';\nimport { explicitStyle } from '../shared/formatting.js';\nimport { BORDER_SIDES,weekBoundaryStyles,withWeekBoundaries } from '../shared/borders.js';\nimport { checkWorkbookArchive } from '../server/archive.mjs';\nimport { FONTS,MIN_FONT_SIZE,MAX_FONT_SIZE,normalizeFont,weeksForYear,weeksForPeriod,periodYears,mondayOf,todayKey,dateKey,displayValue,cell,safeSpreadsheetText,defaultView,savedFilter,viewLayout,fieldsFor,orderColumns,propertiesFor,propertyOption,sampleProperties,textMode,splitNames,canManageTeam,shortId } from '../shared/domain.js';\nimport { requireThat,yearSchema,periodScopeSchema,styleSchema,dateSchema,viewSchema,validateCellValue } from '../server/validation.mjs';\nconst stringSchema=()=>z.string().trim().min(1).max(100);\n`;
  await mkdir(resolve(root, "worker"), { recursive: true });
  await writeFile(
    resolve(root, "worker/transfer-core.mjs"),
    imports + source.slice(start, end),
  );
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await generateTransferCore();
  await mkdir(resolve(root, "dist"), { recursive: true });
  const guide = (await readFile(resolve(root, "docs/CLOUD_SETUP.md"), "utf8"))
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
  await writeFile(
    resolve(root, "dist/CLOUD_SETUP.html"),
    '<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width"><title>GraeBoard Cloud Setup</title><style>body{max-width:80ch;margin:2rem auto;padding:1rem;font:16px/1.7 system-ui}pre{white-space:pre-wrap;overflow-wrap:anywhere}</style><pre>' +
      guide +
      "</pre>",
  );
  if (!process.argv.includes("--generate-only")) {
    const run = spawnSync(
      process.execPath,
      [
        resolve(root, "node_modules/wrangler/bin/wrangler.js"),
        "deploy",
        "--dry-run",
        "--outdir",
        "dist-worker",
      ],
      {
        cwd: root,
        stdio: "inherit",
        env: { ...process.env, WRANGLER_SEND_METRICS: "false" },
      },
    );
    if (run.status !== 0) process.exit(run.status || 1);
  }
}
